import AppKit
import CryptoKit
import Foundation

public enum ClipboardCapture {
    public static let internalMarkerType = NSPasteboard.PasteboardType("io.github.codewarriors0.air-cc.internal")

    private static let ignoredTypes: Set<NSPasteboard.PasteboardType> = [
        internalMarkerType,
        NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"),
        NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
        NSPasteboard.PasteboardType("com.agilebits.onepassword")
    ]

    public static func capture(
        from pasteboard: NSPasteboard = .general,
        sourceApp: NSRunningApplication? = NSWorkspace.shared.frontmostApplication
    ) -> CapturedClipPayload? {
        guard let types = pasteboard.types, !types.isEmpty else { return nil }

        for type in types where ignoredTypes.contains(type) {
            return nil
        }

        let appName = sourceApp?.localizedName
        let bundleID = sourceApp?.bundleIdentifier

        // 1. Check file URLs first (Finder file copy puts both fileURL and icon TIFF)
        if let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: [
            .urlReadingFileURLsOnly: true
        ]) as? [URL], !urls.isEmpty {
            let paths = urls.map { $0.path }.filter { !$0.isEmpty }
            if !paths.isEmpty {
                let joined = paths.joined(separator: "\n")
                let hash = sha256Hex(Data(("files:" + joined).utf8))
                let firstName = URL(fileURLWithPath: paths[0]).lastPathComponent
                let title = paths.count == 1 ? firstName : "\(firstName) 等 \(paths.count) 个文件"

                var thumbData: Data? = nil
                if paths.count == 1, let img = NSImage(contentsOfFile: paths[0]) {
                    thumbData = makeThumbnailPNG(from: img, maxDimension: 160)
                }

                var totalBytes = 0
                for path in paths {
                    if let attrs = try? FileManager.default.attributesOfItem(atPath: path),
                       let size = attrs[.size] as? Int {
                        totalBytes += size
                    }
                }

                return CapturedClipPayload(
                    contentHash: hash,
                    kind: .files,
                    title: title,
                    plainText: joined,
                    thumbnailPNGData: thumbData,
                    filePaths: paths,
                    byteSize: totalBytes,
                    sourceAppName: appName,
                    sourceBundleID: bundleID
                )
            }
        }

        // 2. Check text / rich text before pure image (rich text copies sometimes include a TIFF preview)
        let rawString = pasteboard.string(forType: .string)
        if let rawString, !rawString.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            let rtfData = pasteboard.data(forType: .rtf)
            let htmlData = pasteboard.data(forType: .html)
            let hasRich = (rtfData != nil && !rtfData!.isEmpty) || (htmlData != nil && !htmlData!.isEmpty)
            let kind: ClipKind = hasRich ? .richText : .text
            let title = summarizeText(rawString)
            let utf8Bytes = Data(rawString.utf8)
            let hash = sha256Hex(utf8Bytes)

            return CapturedClipPayload(
                contentHash: hash,
                kind: kind,
                title: title,
                plainText: rawString,
                rtfData: rtfData,
                htmlData: htmlData,
                byteSize: utf8Bytes.count,
                sourceAppName: appName,
                sourceBundleID: bundleID
            )
        }

        // 3. Check pure image (screenshots, browser copy image, image editors)
        if let imageResult = extractImage(from: pasteboard) {
            let hash = sha256Hex(imageResult.pngData)
            let title = "图片 (\(imageResult.width)×\(imageResult.height))"
            return CapturedClipPayload(
                contentHash: hash,
                kind: .image,
                title: title,
                plainText: title,
                imagePNGData: imageResult.pngData,
                thumbnailPNGData: imageResult.thumbnailData,
                imageWidth: imageResult.width,
                imageHeight: imageResult.height,
                byteSize: imageResult.pngData.count,
                sourceAppName: appName,
                sourceBundleID: bundleID
            )
        }

        return nil
    }

    public static func summarizeText(_ text: String, maxLength: Int = 180) -> String {
        let lines = text
            .components(separatedBy: .newlines)
            .map { $0.trimmingCharacters(in: .whitespaces) }
            .filter { !$0.isEmpty }
        let joined = lines.joined(separator: " ↵ ")
        if joined.count <= maxLength {
            return joined
        }
        let idx = joined.index(joined.startIndex, offsetBy: maxLength)
        return String(joined[..<idx]) + "…"
    }

    public static func sha256Hex(_ data: Data) -> String {
        let digest = SHA256.hash(data: data)
        return digest.map { String(format: "%02x", $0) }.joined()
    }

    private static func extractImage(from pasteboard: NSPasteboard) -> (pngData: Data, thumbnailData: Data?, width: Int, height: Int)? {
        var rawImageData: Data? = pasteboard.data(forType: .png)
        if rawImageData == nil {
            rawImageData = pasteboard.data(forType: .tiff)
        }

        let nsImage: NSImage?
        if let rawImageData {
            nsImage = NSImage(data: rawImageData)
        } else if NSImage.canInit(with: pasteboard) {
            nsImage = NSImage(pasteboard: pasteboard)
        } else {
            nsImage = nil
        }

        guard let image = nsImage else { return nil }
        guard let rep = bitmapRep(from: image) else { return nil }
        let width = rep.pixelsWide
        let height = rep.pixelsHigh
        guard width > 0 && height > 0 else { return nil }

        let pngData: Data
        if let directPNG = pasteboard.data(forType: .png), !directPNG.isEmpty {
            pngData = directPNG
        } else if let encoded = rep.representation(using: .png, properties: [:]) {
            pngData = encoded
        } else {
            return nil
        }

        let thumb = makeThumbnailPNG(from: image, maxDimension: 240)
        return (pngData, thumb, width, height)
    }

    private static func bitmapRep(from image: NSImage) -> NSBitmapImageRep? {
        for rep in image.representations {
            if let bitmap = rep as? NSBitmapImageRep {
                return bitmap
            }
        }
        guard let tiff = image.tiffRepresentation else { return nil }
        return NSBitmapImageRep(data: tiff)
    }

    public static func makeThumbnailPNG(from image: NSImage, maxDimension: CGFloat) -> Data? {
        guard let srcRep = bitmapRep(from: image) else { return nil }
        let srcW = CGFloat(srcRep.pixelsWide)
        let srcH = CGFloat(srcRep.pixelsHigh)
        guard srcW > 0, srcH > 0 else { return nil }

        let scale = min(1.0, maxDimension / max(srcW, srcH))
        let dstW = max(1, Int(round(srcW * scale)))
        let dstH = max(1, Int(round(srcH * scale)))

        guard let targetRep = NSBitmapImageRep(
            bitmapDataPlanes: nil,
            pixelsWide: dstW,
            pixelsHigh: dstH,
            bitsPerSample: 8,
            samplesPerPixel: 4,
            hasAlpha: true,
            isPlanar: false,
            colorSpaceName: .deviceRGB,
            bytesPerRow: 0,
            bitsPerPixel: 0
        ) else {
            return nil
        }

        NSGraphicsContext.saveGraphicsState()
        if let ctx = NSGraphicsContext(bitmapImageRep: targetRep) {
            NSGraphicsContext.current = ctx
            ctx.imageInterpolation = .high
            image.draw(
                in: NSRect(x: 0, y: 0, width: CGFloat(dstW), height: CGFloat(dstH)),
                from: .zero,
                operation: .copy,
                fraction: 1.0
            )
        }
        NSGraphicsContext.restoreGraphicsState()

        return targetRep.representation(using: .png, properties: [:])
    }
}
